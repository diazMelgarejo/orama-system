#!/usr/bin/env bash
# install_openclaw_runtime_watch.sh — install/uninstall the OpenClaw runtime drift watcher (macOS launchd)
#
# Every 30 minutes (and at login) it runs the read-only runtime check from Perpetua-Tools and posts a macOS
# notification when the gateway service names a node version or the stable node link has drifted. It ALERTS ONLY:
# it never rewrites the service, because an automatic repoint could move the gateway onto a half-migrated node.
# Fix a reported drift on purpose with:  python -m perpetua_tools.openclaw_runtime --apply
#
# Usage:
#   ./scripts/install_openclaw_runtime_watch.sh               # install (idempotent)
#   ./scripts/install_openclaw_runtime_watch.sh --uninstall
#   ./scripts/install_openclaw_runtime_watch.sh --status
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_DIR="$(dirname "$SCRIPT_DIR")"
# shellcheck source=../bin/orama-system/scripts/lib/openclaw-env.sh
source "$REPO_DIR/bin/orama-system/scripts/lib/openclaw-env.sh"

LABEL="com.orama.openclaw-runtime-watch"
LAUNCH_AGENTS="$HOME/Library/LaunchAgents"
PLIST_DEST="$LAUNCH_AGENTS/$LABEL.plist"
STATE_DIR="$HOME/.local/state/openclaw-runtime"
WRAPPER="$STATE_DIR/watch-run.sh"
INTERVAL_SECONDS=1800

PT_ROOT="${PERPETUA_TOOLS_ROOT:-${PERPETUATOOLSROOT:-}}"
[ -n "$PT_ROOT" ] || PT_ROOT="$(detect_perpetua_tools_root 2>/dev/null || true)"

_status() {
  if launchctl list 2>/dev/null | grep -q "$LABEL"; then echo "loaded: $LABEL"; else echo "NOT loaded: $LABEL"; fi
  [ -f "$STATE_DIR/last_check.json" ] && { echo "--- last check ---"; cat "$STATE_DIR/last_check.json"; } || true
}

_uninstall() {
  launchctl unload "$PLIST_DEST" 2>/dev/null || true
  rm -f "$PLIST_DEST"
  echo "uninstalled $LABEL"
}

_install() {
  [ -n "$PT_ROOT" ] || { echo "install_openclaw_runtime_watch: Perpetua-Tools root not found (set PERPETUA_TOOLS_ROOT)" >&2; exit 1; }
  mkdir -p "$LAUNCH_AGENTS" "$STATE_DIR"
  local python3_bin pt_root_q state_dir_q py_bin_q
  python3_bin="$(command -v python3 || true)"
  [ -n "$python3_bin" ] || { echo "install_openclaw_runtime_watch: no python3 found" >&2; exit 1; }
  printf -v pt_root_q '%q' "$PT_ROOT"
  printf -v state_dir_q '%q' "$STATE_DIR"
  printf -v py_bin_q '%q' "$python3_bin"
  cat > "$WRAPPER" <<WRAPPER_EOF
#!/bin/bash
# Auto-generated by install_openclaw_runtime_watch.sh — do not edit. Read-only check; alerts, never fixes.
export PYTHONPATH=${pt_root_q}/src
OUT=${state_dir_q}
if ${py_bin_q} -m perpetua_tools.openclaw_runtime --check --json > "\$OUT/last_check.json" 2> "\$OUT/last_check.err"; then
  exit 0
fi
/usr/bin/osascript -e 'display notification "The OpenClaw gateway service names a node version or the node link drifted. Run: openclaw gateway status" with title "OpenClaw runtime drift"' || true
WRAPPER_EOF
  chmod +x "$WRAPPER"
  python3 - "$PLIST_DEST" "$LABEL" "$WRAPPER" "$INTERVAL_SECONDS" <<'EOF'
import plistlib, sys
dest, label, wrapper, interval = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
doc = {
    "Label": label,
    "ProgramArguments": ["/bin/bash", wrapper],
    "RunAtLoad": True,
    "StartInterval": interval,
}
with open(dest, "wb") as f:
    plistlib.dump(doc, f)
EOF
  launchctl unload "$PLIST_DEST" 2>/dev/null || true
  launchctl load "$PLIST_DEST"
  echo "installed $LABEL (checks every ${INTERVAL_SECONDS}s; alerts only)"
  _status
}

case "${1:-}" in
  --uninstall) _uninstall ;;
  --status) _status ;;
  *) _install ;;
esac
